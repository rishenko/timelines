"""
Event categories for Ancient and Classical, which has no generator: its source file (data-src/ancient-classical.json)
is kept by the content scripts and plans in scripts/. This runs the shared classifier (pipelines/common/event_categories.py)
over that file, with this folder's reviewed overrides (categories.json), and writes:

  data-src/ancient-classical-categories.json            the plan: the `category` facet, and each event's categories
                                                         (main first). `npm run data -- importance ancient-classical`
                                                         applies it (scripts/lib/categories.ts), so the build and CI need
                                                         no dump.
  data-src/provenance/ancient-classical-categories.json  the evidence for each event's categories, as the generators
                                                         write it; an event with an empty list is still to review.

    pipelines/.venv/bin/python -I pipelines/ancient/categories.py [--data DIR] [--dump NAME]
    npm run data -- importance ancient-classical

Rerunning on the same dump, source file and overrides writes the same bytes.
"""
import copy
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PIPELINES = os.path.dirname(HERE)
REPO = os.path.dirname(PIPELINES)
sys.path[:0] = [os.path.join(PIPELINES, 'common')]
from settings import take_flags  # noqa: E402

take_flags(sys.argv)
import event_categories  # noqa: E402

SOURCE = os.path.join(REPO, 'data-src', 'ancient-classical.json')
PLAN = os.path.join(REPO, 'data-src', 'ancient-classical-categories.json')
EVIDENCE = os.path.join(REPO, 'data-src', 'provenance', 'ancient-classical-categories.json')
OVERRIDES = os.path.join(HERE, 'categories.json')


def main():
    data = copy.deepcopy(json.load(open(SOURCE, encoding='utf-8')))
    counts = event_categories.apply(data, OVERRIDES, EVIDENCE)
    events = {}
    for e in data['events']:
        values = [m['value'] for m in e.get('memberships', []) if m['facet'] == 'category']
        if values:
            events[e['uuid']] = values
    plan = {
        '_note': 'Generated by pipelines/ancient/categories.py (the shared classifier, plus pipelines/ancient/categories.json, '
                 'the reviewed overrides). Don\'t edit: change the overrides and rerun it.',
        'facet': data['meta']['facets']['category'],
        'events': dict(sorted(events.items())),
    }
    with open(PLAN, 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(plan, indent=1, ensure_ascii=False) + '\n')
    print(f'categories: {counts}; {len(events)} events in {os.path.relpath(PLAN, REPO)}')


if __name__ == '__main__':
    main()
