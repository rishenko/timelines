"""
Golden ages and eras for Ancient and Classical, which has no generator: resolves its entries of
pipelines/common/periods.json against the dump (pipelines/common/periods.py) and writes the plan the build applies,
data-src/ancient-classical-periods.json (meta.eras, the new golden-age events and the sources they cite).

    pipelines/.venv/bin/python -I pipelines/ancient/periods.py [--data DIR] [--dump NAME]

Then, in this order (each step reads what the one before wrote):
    npm run data -- importance ancient-classical      applies the periods plan, then importance, row links, memberships, categories
    pipelines/.venv/bin/python -I pipelines/ancient/categories.py
    npm run data -- importance ancient-classical
Key events go in the importance plan (data-src/ancient-classical-importance.json), which sets every event's importance.
Rerunning on the same dump and periods.json writes the same bytes.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PIPELINES = os.path.dirname(HERE)
REPO = os.path.dirname(PIPELINES)
sys.path[:0] = [os.path.join(PIPELINES, 'common')]
from settings import take_flags  # noqa: E402

take_flags(sys.argv)
import periods  # noqa: E402

PLAN = os.path.join(REPO, 'data-src', 'ancient-classical-periods.json')


def main():
    p = periods.plan('ancient-classical')
    p = {'_note': 'Generated by pipelines/ancient/periods.py from pipelines/common/periods.json (dates checked against the '
                  'Wikipedia dump). Don\'t edit: change periods.json and rerun it.', **p}
    with open(PLAN, 'w', encoding='utf-8') as f:
        f.write(json.dumps(p, indent=1, ensure_ascii=False) + '\n')
    print(f'periods: {len(p["eras"])} eras, {len(p["events"])} events, {len(p["sources"])} sources in {os.path.relpath(PLAN, REPO)}')


if __name__ == '__main__':
    main()
