"""
Generated place -> row table for the v2 emitters: each timeline row that links a Wikipedia article (its `url`) is the row of that
article's Wikidata item, with its region group (`parent`), so an event whose place or combatant is that article lands on that row.

    pipelines/extract/.venv/bin/python -I pipelines/v2/build_places.py     # reads public/timelines/*.json and the extract DB

Writes $TIMELINES_DATA/v2/places.generated.json (derived data stays out of the repo, like the candidates): {qid: {name, rows: {timeline: [{row, parent}]}}}. The hand-kept places.json wins where it names the
same QID (it also carries the dated rows). Rerun after a timeline's rows change.
"""
import json
import os
import sqlite3
import sys
from urllib.parse import unquote

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path[:0] = [os.path.join(ROOT, 'pipelines', 'common')]
import settings  # noqa: E402

settings.take_flags(sys.argv[1:])


OUT = os.path.join(settings.DATA, 'v2', 'places.generated.json')  # derived from the compiled timelines: kept out of the repo, like the candidates


def main():
    db = sqlite3.connect(f'file:{os.path.join(settings.WIKIPEDIA, "extract-" + settings.DUMP_NAME + ".sqlite")}?mode=ro', uri=True)

    def qid(title):
        r = db.execute('SELECT q.qid FROM page p JOIN qid q ON q.page_id=p.page_id WHERE p.title=? AND p.ns=0', (title,)).fetchone()
        if not r:
            r = db.execute('SELECT q.qid FROM page p JOIN page t ON t.title=p.redirect_to JOIN qid q ON q.page_id=t.page_id WHERE p.title=? AND p.ns=0', (title,)).fetchone()
        return r[0] if r else None

    out, miss = {}, []
    for tl in ('ancient-classical', 'medieval', 'modern-states'):
        for t in json.load(open(os.path.join(ROOT, 'public', 'timelines', f'{tl}.json'), encoding='utf-8'))['tracks']:
            url = t.get('url') or ''
            if '/wiki/' not in url:
                continue
            title = unquote(url.split('/wiki/', 1)[1]).replace('_', ' ')
            q = qid(title)
            if not q:
                miss.append(f'{tl}/{t["id"]}: {title}'); continue
            e = out.setdefault(q, {'name': title, 'rows': {}})
            sp = t.get('span')
            stretches = [x for x in (sp if isinstance(sp, list) else [sp] if sp else []) + t.get('phases', []) if x and x.get('start') is not None]
            life = sorted(([x['start'], None if x.get('ongoing') else x.get('end')] for x in stretches), key=lambda a: (a[0], a[1] is None, a[1] or 0))
            e['rows'].setdefault(tl, []).append({'row': t['id'], 'parent': t.get('parent'), 'life': life})
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump({'_note': 'Generated by build_places.py from the compiled timelines; do not edit.', 'places': out}, open(OUT, 'w', encoding='utf-8', newline='\n'), indent=0, ensure_ascii=False)
    print(len(out), 'places;', len(miss), 'rows with no item:', *miss[:6])


if __name__ == '__main__':
    main()
