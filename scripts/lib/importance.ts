// Event importance: 1 = key, 2 = normal (stored as no field), 3 = minor. Applying an importance plan to a
// source file, and writing the review list of key and minor events. Used by scripts/data.ts (importance),
// scripts/set-importance.ts and scripts/list-importance.ts.
import { formatYear } from '../../src/lib/calendar.ts';
import type { Calendar } from '../../src/types.ts';

interface Ev { uuid: string; title: string; start: number; end?: number; circa?: boolean; tracks: string[]; importance?: number }
interface Tr { id: string; name: string; parent?: string }

/** Sets one event's importance; 2 (normal) removes the field. Throws on an unknown uuid. */
export function setImportance(events: { uuid: string; importance?: number }[], uuid: string, level: number) {
  if (![1, 2, 3].includes(level)) throw new Error('importance must be 1, 2 or 3');
  const e = events.find((x) => x.uuid === uuid);
  if (!e) throw new Error(`unknown event "${uuid}"`);
  if (level === 2) delete e.importance;
  else e.importance = level;
}

/**
 * Applies a plan { "1": [uuids], "3": [uuids] } to a source file's events (in place). Every uuid the plan
 * doesn't list is reset to normal, so the plan is the whole truth about importance and can be re-run safely.
 * Keys other than "1", "2", "3" (such as "_rubric") are notes.
 */
export function applyImportancePlan(events: { uuid: string; importance?: number }[], plan: Record<string, unknown>) {
  for (const e of events) delete e.importance;
  for (const [level, ids] of Object.entries(plan))
    if (['1', '2', '3'].includes(level)) for (const id of ids as string[]) setImportance(events, id, Number(level));
}

export function importanceCounts(events: { importance?: number }[]) {
  const count = (n: number) => events.filter((e) => (e.importance ?? 2) === n).length;
  return { key: count(1), normal: count(2), minor: count(3) };
}

/**
 * The review list of a compiled timeline's key and minor events, grouped by region, as Markdown. When the
 * top-level rows are groups of regions (they have grandchildren), each group gets a heading and each region
 * inside it a sub-heading. `short` names the plan and npm command ("ancient" → data-src/ancient-importance.json).
 */
export function keyEventsMarkdown(
  d: { meta: { title: string; calendar: Calendar }; tracks: Tr[]; events: Ev[] },
  short: string,
): string {
  const byId = new Map(d.tracks.map((t) => [t.id, t]));
  const kids = (id: string) => d.tracks.filter((t) => t.parent === id);
  const isGroup = (id: string) => kids(id).some((k) => kids(k.id).length > 0);
  /** The section an event's row falls in: a region inside a group, else the top-level row. */
  const sectionOf = (id: string) => {
    let t = byId.get(id)!;
    while (t.parent && !(byId.get(t.parent)!.parent === undefined && isGroup(t.parent))) t = byId.get(t.parent)!;
    return t.id;
  };
  const year = (y: number) => formatYear(y, d.meta.calendar);
  const when = (e: Ev) => (e.circa ? 'c. ' : '') + year(e.start) + (e.end !== undefined && e.end !== e.start ? `–${year(e.end)}` : '');
  const rowNames = (e: Ev) => e.tracks.map((t) => byId.get(t)!.name).join(', ');

  const { key, normal, minor } = importanceCounts(d.events);
  const lines: string[] = [
    `# ${d.meta.title}: key and minor events`,
    '',
    `Generated by \`scripts/list-importance.ts\`. Key events are bold and placed first in crowded or collapsed`,
    `rows; minor ones fold into "+N" first. To change one, edit \`data-src/${short}-importance.json\`, then run`,
    `\`npm run importance:${short}\`.`,
    '',
    `Totals: ${key} key, ${normal} normal, ${minor} minor (${d.events.length} events).`,
    '',
  ];

  const section = (r: Tr, h: string) => {
    // an event belongs to the section of its first row
    const evs = d.events.filter((e) => sectionOf(e.tracks[0]) === r.id).sort((a, b) => a.start - b.start);
    if (!evs.length) return;
    const keyEvs = evs.filter((e) => e.importance === 1);
    const minorEvs = evs.filter((e) => e.importance === 3);
    lines.push(`${h} ${r.name}`, '', `${keyEvs.length} key, ${evs.length - keyEvs.length - minorEvs.length} normal, ${minorEvs.length} minor.`, '');
    if (keyEvs.length) {
      lines.push('**Key**', '');
      for (const e of keyEvs) lines.push(`- ${e.title} (${when(e)}; ${rowNames(e)}) \`${e.uuid}\``);
      lines.push('');
    }
    if (minorEvs.length) {
      lines.push('**Minor**', '');
      for (const e of minorEvs) lines.push(`- ${e.title} (${when(e)}) \`${e.uuid}\``);
      lines.push('');
    }
  };
  for (const r of d.tracks.filter((t) => !t.parent)) {
    if (!isGroup(r.id)) {
      section(r, '##');
      continue;
    }
    lines.push(`## ${r.name}`, '');
    section(r, '###'); // events placed on the group row itself, if any
    for (const k of kids(r.id)) section(k, '###');
  }
  return lines.join('\n');
}
