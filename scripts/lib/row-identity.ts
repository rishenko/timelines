// R4 (ontology review): what a row id shared by two timelines means. A shared id is `same` when both rows resolve to the same Wikidata item and
// `namesake` when they resolve to different items (Armenia the kingdom and Armenia the country). Rows with no Wikidata item (region groups, themes,
// an article without an item) are decided by hand in pipelines/common/row-identity-hand.json, each with a reason. Nothing is renamed: the file only
// says what the shared ids mean, so links, people placement and tours can lean on it.
export type Row = { id: string; name?: string; url?: string; ids?: { wikidata?: string } };
export type Verdict = 'same' | 'namesake';
export type Hand = Record<string, { verdict: Verdict; reason: string }>; // key: "<timelineA>|<timelineB>|<row id>"
export type Entry = {
  id: string;
  between: [string, string];
  verdict: Verdict;
  basis: 'wikidata' | 'hand';
  a: { name: string; wikidata: string | null };
  b: { name: string; wikidata: string | null };
  reason?: string;
};

export const TIMELINES = ['ancient-classical', 'medieval', 'modern-states'];
export const PAIRS: [string, string][] = [['ancient-classical', 'medieval'], ['medieval', 'modern-states'], ['ancient-classical', 'modern-states']];

/** The entries and the problems for the shared ids of every pair of timelines. */
export function classify(rows: Record<string, Row[]>, hand: Hand): { entries: Entry[]; problems: string[] } {
  const entries: Entry[] = [];
  const problems: string[] = [];
  const used = new Set<string>();
  for (const [a, b] of PAIRS) {
    const bById = new Map(rows[b].map((r) => [r.id, r]));
    for (const ra of rows[a]) {
      const rb = bById.get(ra.id);
      if (!rb) continue;
      const qa = ra.ids?.wikidata ?? null;
      const qb = rb.ids?.wikidata ?? null;
      const key = `${a}|${b}|${ra.id}`;
      const side = (r: Row, q: string | null) => ({ name: r.name ?? '', wikidata: q });
      if (qa && qb) {
        if (hand[key]) problems.push(`${key}: has a hand entry but both rows now carry a Wikidata id; remove the entry`);
        entries.push({ id: ra.id, between: [a, b], verdict: qa === qb ? 'same' : 'namesake', basis: 'wikidata', a: side(ra, qa), b: side(rb, qb) });
      } else if (hand[key]) {
        used.add(key);
        entries.push({ id: ra.id, between: [a, b], verdict: hand[key].verdict, basis: 'hand', a: side(ra, qa), b: side(rb, qb), reason: hand[key].reason });
      } else {
        problems.push(`${key}: shared by both timelines but at least one row has no Wikidata id and there is no hand entry (add one with a reason)`);
      }
    }
  }
  for (const k of Object.keys(hand)) if (!used.has(k) && !problems.some((p) => p.startsWith(k + ':'))) problems.push(`${k}: hand entry for a row that is not shared by that pair any more; remove it`);
  entries.sort((x, y) => x.id.localeCompare(y.id) || x.between.join().localeCompare(y.between.join()));
  return { entries, problems };
}

export const render = (entries: Entry[]) =>
  JSON.stringify({
    note: 'Generated by `node scripts/row-identity.ts` (the regen route) from the rows\' ids.wikidata and pipelines/common/row-identity-hand.json. `same`: both rows are one Wikidata item. `namesake`: two items share a row id. Nothing is renamed.',
    schema: 1,
    counts: entries.reduce<Record<string, number>>((c, e) => ((c[`${e.between.join('/')} ${e.verdict}`] = (c[`${e.between.join('/')} ${e.verdict}`] ?? 0) + 1), c), {}),
    entries,
  }, null, 1) + '\n';
